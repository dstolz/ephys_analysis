function setSessionPreviewState(obj, state, opts)
%setSessionPreviewState  Show where the Sessions tab's preview is: its badge, and a card over it while busy.
%   setSessionPreviewState(obj, STATE) is setPreviewState for the session
%   plot's preview (SessionPreviewPanel, SessionPreviewBadge,
%   SessionPreviewButton; the state in SessionPreviewState; the card's
%   Cancel calls onCancelSessionPreview), with the same states:
%     idle       no preview (no session plot, no scan, no dataset)
%     computing  the base plot is computed on the sessions (cancelable)
%     drawing    the merged result is being drawn
%     drawn      the preview is the session plot as it is now
%     stale      the session plot, its base plot, the defaults or the
%                ticks changed since it was drawn: press Preview
%     skipped    it cannot be drawn (no base plot, too few sessions ...)
%     failed     computing or drawing it failed
%     canceled   Cancel stopped the compute
%   ("waiting" is accepted but not used here.)
arguments
    obj (1,1) EphysAnalysisApp
    state (1,1) string {mustBeMember(state, ["idle" "computing" "drawing" "drawn" "stale" "waiting" "skipped" "failed" "canceled"])}
    opts.Message (1,1) string = ""
end
tips = struct( ...
    'idle', "Nothing is previewed: add a session plot, scan and tick the datasets.", ...
    'computing', "Computing the base plot on every session (the results are kept, so a second preview is quick).", ...
    'drawing', "Drawing the merged plot.", ...
    'drawn', "The preview is the session plot as it is now.", ...
    'stale', "The session plot, its base plot, the Alignment defaults or the datasets ticked changed since this " + ...
        "preview was drawn, and it was not redrawn (Auto is off, or the last preview took " + obj.AutoPreviewSeconds + ...
        " s or more): press Preview.", ...
    'skipped', "This session plot cannot be drawn (the line below says why).", ...
    'failed', "The preview failed (the line below and the Log tab say why).", ...
    'canceled', "The preview was canceled before the sessions were computed: press Preview.");
P = struct('Panel', obj.SessionPreviewPanel, 'Badge', obj.SessionPreviewBadge, 'StateProp', "SessionPreviewState", ...
    'CancelFcn', @() obj.onCancelSessionPreview(), 'Button', obj.SessionPreviewButton, 'Tips', tips);
showPreviewState(obj, P, state, Message=opts.Message);
end
