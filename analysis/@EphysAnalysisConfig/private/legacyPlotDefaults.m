function s = legacyPlotDefaults(section)
%legacyPlotDefaults  The defaults of a version-1 config's plot sections, for its migration only.
%   S = legacyPlotDefaults(SECTION) is what EphysAnalysisConfig.defaults
%   gave for SECTION in config version 1: "Plot" (one entry of Plots),
%   "SessionPlot" (one entry of SessionPlots) and "Aux" (a plot's mean aux
%   signal). Version 2 has no Plots or SessionPlots: a version-1 file's are
%   read with these defaults (legacyNormalizePlot, legacyMigrate) and
%   converted to figures on load (legacyPlotToFigure). Nothing else uses
%   them.
%
%   See also legacyMigrate, legacyNormalizePlot, legacyPlotToFigure,
%   EphysAnalysisConfig.defaults.

arguments
    section (1,1) string
end

switch section
    case "Aux"
        % a psth / raster plot of spikes: the mean aux (accelerometer) signal over the plot's epochs
        s = struct( ...
            'mode',           "off", ...       % "off" | "channels" | "magnitude"
            'channels',       [], ...          % columns of the AUX extract ([] = all)
            'placement',      "below", ...     % "below" | "above" | "over"
            'display',        "lines", ...     % "lines" | "stacked" | "heatmap"
            'statistic',      "mean", ...      % "mean" | "median"
            'transform',      "none", ...      % "none" | "rectify"
            'errorType',      "sem", ...       % "off" | "sem" | "std" | "ci95" | "iqr"
            'colorBy',        "auto", ...      % "auto" | "group" | "channel"
            'baseline',       "none", ...      % "none" | "subtract"
            'baselineWindow', [-0.2 0], ...
            'byGroup',        true, ...
            'yLim',           [], ...
            'overPosition',   [0 1]);

    case "Plot"
        u = EphysAnalysisConfig.defaults("UnitSelection");
        s = struct( ...
            'id',            "", ...
            'kind',          "psth", ...        % one of legacyPlotKinds().Kind
            'enabled',       true, ...
            'title',         "", ...
            'source',        "units", ...       % units | detected | LFP | MUA | SPIKE | AUX | trials
            'units',         rmfield(u, 'source'), ...
            'channels',      [], ...
            'ref',           "default", ...     % "default" or an EventRef
            'window',        "default", ...     % "default" or an EpochWindow
            'selection',     "default", ...     % "default" or a TrialSelection
            'bins',          struct('BinSec', 0.01, 'SmoothSec', 0.01), ...
            'measure',       "rate", ...
            'baseline',      struct('Mode', "none", 'Window', [-0.2 0]), ...
            'auroc',         EphysAnalysisConfig.defaults("Auroc"), ...
            'layout',        "", ...            % "" = the kind's default layout
            'withRaster',    true, ...
            'rasterSort',    "", ...
            'rasterSortEvent', [], ...
            'rasterSortOrder', "ascending", ...
            'rasterByGroup', true, ...
            'rasterEvents',  repmat(EphysAnalysisConfig.defaults("EventMark"), 1, 0), ...
            'histStyle',     "bar", ...
            'fill',          true, ...
            'fillAlpha',     NaN, ...
            'normalize',     "none", ...
            'stack',         false, ...
            'stackSpacing',  1.1, ...
            'stackRaster',   false, ...
            'stackRasterEqual', false, ...
            'stackRasterTrials', Inf, ...
            'maskAfterStop', false, ...
            'param',         "", ...
            'seriesParam',   "", ...
            'yParam',        "", ...
            'jitter',        true, ...
            'xScale',        "category", ...
            'value',         "rate", ...
            'order',         "probe", ...
            'metric',        "mean", ...
            'correlation',   "pearson", ...
            'fisherZ',       false, ...
            'waveform',      EphysAnalysisConfig.defaults("Waveform"), ...
            'aux',           legacyPlotDefaults("Aux"), ...
            'note',          EphysAnalysisConfig.defaults("Note"), ...
            'overlays',      repmat(EphysAnalysisConfig.defaults("Overlay"), 1, 0), ...
            'style',         EphysAnalysisConfig.defaults("Style"), ...
            'aesthetics',    PlotAesthetics.emptyRules());

    case "SessionPlot"
        % one plot over several sessions: a base plot (by id) drawn per dataset and merged
        s = struct( ...
            'id',          "", ...
            'enabled',     true, ...
            'title',       "", ...
            'plot',        "", ...                  % id of the base plot
            'layout',      "", ...                  % "" = the base plot's
            'datasets',    "ticked", ...            % "ticked" | "list"
            'datasetKeys', string.empty(1,0), ...
            'facet',       "none", ...
            'series',      "session", ...
            'colorOrder',  "palette", ...
            'showMembers', false, ...
            'error',       "sem", ...
            'match',       "pool", ...              % "pool" | "site" | "mapping"
            'mappingFile', "", ...
            'minSessions', 1, ...
            'trialGroups', "pool", ...
            'data',        "results", ...           % "results" | "epochs" | "signals" (a list)
            'aesthetics',  PlotAesthetics.emptyRules());

    otherwise
        error('EphysAnalysisConfig:BadSection', 'Unknown version-1 plot section "%s".', section);
end
end
