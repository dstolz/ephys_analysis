function keys = figureRoleSettings(role)
%figureRoleSettings  The figure editor's settings that control a drawn part, most likely first.
%   KEYS = figureRoleSettings(ROLE) names, for a part's role (the roles of
%   PlotAesthetics.roles), the figure editor's rows that decide how it
%   looks or whether it is drawn, as a string row. A key is a formRow key
%   of buildFiguresTab ("errorType", "fontSize"), or "@" and a section's name
%   ("@style") for a part with no row of its own. The right-click menu's
%   "Go to setting" goes to the first one the figure shows for the panel
%   (EphysFigGenApp.gotoFigureSetting), the next when a row is hidden
%   (an option of another panel type). A role with no entry gives "@style"
%   (the Style section).
%
%   See also PlotAesthetics.roles, EphysFigGenApp.gotoFigureSetting.
role = string(role);
M = map();
if isfield(M, role)
    keys = M.(role);
else
    keys = "@style";
end
end


