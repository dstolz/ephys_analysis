function notes = notesOf(warnings, head)
%notesOf  The notes of the LoadWarnings that start with HEAD, HEAD removed.
notes = warnings(startsWith(warnings, head));
notes = extractAfter(notes, strlength(head));
if isempty(notes); notes = string.empty(1, 0); end
end


function rmdirQuiet(root)
if isfolder(root)
    try
        rmdir(root, 's');
    catch
    end
end
