function onShowShortcuts(obj)
%onShowShortcuts  Help > Keyboard shortcuts and right-click menus: a small window that lists them.
%   The window is not modal and opens once; asking again brings it to the
%   front. Its text is shortcutText, which says where each key works (the
%   plots act only with the pointer over them).
%
%   See also showVizHelp, buildMenus.
h = obj.ShortcutsFig;
if ~isempty(h) && isvalid(h)
    figure(h);
    return
end
h = AppDialog.showText("Keyboard shortcuts and right-click menus", splitlines(shortcutText()), ...
    Parent=obj.Fig, Size=[600 600]);
obj.ShortcutsFig = h;
addlistener(obj.Fig, 'ObjectBeingDestroyed', @(~, ~) closeIt(h));
end


function closeIt(h)
if isvalid(h); delete(h); end
end


