function H = ks4ParamHelp()
%ks4ParamHelp  What each Kilosort4 parameter of kilosortParamSpec is, does and how to tune it.
%   H = ks4ParamHelp() returns a struct with one field per parameter name
%   of EphysPipelineConfig.kilosortParamSpec. Each holds the text the
%   window opened by clicking a parameter's name on the Sorting tab shows
%   (showKS4ParamInfo):
%     definition  what the parameter is, with its units
%     function    what Kilosort4 does with it
%     impact      what raising or lowering it changes in the sort
%     tuning      when and how to change it
%     ks4default  Kilosort4's own default (the pipeline's default comes
%                 from the spec), or why there is none
%
%   Checked against the installed Kilosort4 4.1.7 (kilosort/parameters.py
%   and the code that reads each setting). shank_spacing is the pipeline's
%   own (see kilosortParamSpec).

H = struct();

% --- Data ---------------------------------------------------------------
H.n_chan_bin = entry( ...
    "Total number of channels stored in the .bin file, including any channel that holds no ephys data.", ...
    "Tells Kilosort4 how to cut the flat int16 stream into channels x samples.", ...
    "A wrong value scrambles every channel: the sort fails or finds nonsense.", ...
    "Leave blank: the pipeline fills it in from the .bin it writes. Set it only when sorting a .bin written elsewhere.", ...
    "none (required)");
H.fs = entry( ...
    "Sampling rate of the .bin, in Hz.", ...
    "Converts samples to time: the high-pass filter design, tmin / tmax, duplicate_spike_ms and the refractory-period checks of the ACG / CCG tests.", ...
    "A wrong value moves the filter cutoff and breaks the refractory checks that label and merge units.", ...
    "Leave blank: the pipeline takes it from the recording.", ...
    "30000");
H.tmin = entry( ...
    "Time, in s from the start of the recording, at which the data used for sorting begin.", ...
    "Batches before tmin are skipped.", ...
    "Spikes before tmin are not sorted.", ...
    "Keep 0. Raise it to skip a noisy start (the probe settling after insertion) or, with tmax, to sort a short stretch as a quick test.", ...
    "0");
H.tmax = entry( ...
    "Time, in s from the start of the recording, at which the data used for sorting end. Infinity = the end of the recording.", ...
    "Batches after tmax are skipped.", ...
    "Spikes after tmax are not sorted.", ...
    "Keep Infinity. Lower it to drop a damaged end of the recording or to sort a short test stretch.", ...
    "Infinity");

% --- Preprocessing ------------------------------------------------------
H.highpass_cutoff = entry( ...
    "Cutoff frequency, in Hz, of the Butterworth high-pass filter Kilosort4 applies to the data.", ...
    "Removes the LFP and slow drifts before whitening, spike detection and template matching. The pipeline writes the .bin unfiltered, so this is the only spike-band filter.", ...
    "Higher removes more low-frequency noise and sharpens spikes, but shrinks broad (slow) waveforms. Lower keeps more LFP, which raises the noise floor and the false detections.", ...
    "300 Hz suits most data. Try 400-500 when LFP or movement noise leaks into the detections; 150-250 for units with broad waveforms.", ...
    "300");
H.whitening_range = entry( ...
    "Number of nearest channels used to whiten each channel.", ...
    "Builds a local whitening matrix that decorrelates each channel from its neighbors, removing noise they share and equalizing the noise level across channels. All thresholds are in whitened units.", ...
    "More channels removes broader shared noise, but on a small probe whitens across most of it. Fewer channels removes less shared noise.", ...
    "32 is fine for dense probes; with fewer sites Kilosort4 uses them all. On a multi-shank probe, keep the whitening on one shank with shank_spacing.", ...
    "32");
H.shank_spacing = entry( ...
    "Extra distance, in um, put between neighboring shanks for sorting only. 0 = the probe as it is.", ...
    "Not a Kilosort4 setting: the pipeline sorts with a copy of the probe whose shanks are this much further apart along x. The steps that pick channels by distance (whitening, nearest channels, template placement, clustering) then stay on one shank. The probe map is not changed, and the sorted output gets the true site positions back.", ...
    "Stops whitening and templates from mixing sites of different shanks, which share no units.", ...
    "0 for a single shank. For shanks a few hundred um apart or less, a value well beyond the whitening and template footprint (for example 500) keeps the shanks apart.", ...
    "not a Kilosort4 setting");
H.artifact_threshold = entry( ...
    "Amplitude at or above which a whole batch is zeroed out. Infinity = off. Raw ADC counts, not volts: for Intan and Open Ephys headstages 1 count = 0.195 uV, so 5000 is about 1 mV.", ...
    "Applied after Kilosort4's high-pass filter and common reference, before whitening: any batch with an absolute value at or above the threshold is set to zero.", ...
    "Removes large transients, but each hit deletes a whole batch (batch_size samples) and every spike in it. Too low a value throws away good data.", ...
    "Keep Infinity: the pipeline already erases the artifact periods (Artifacts tab) in the .bin. Set it only when big transients remain, well above the largest spikes.", ...
    "Infinity (off)");
H.nskip = entry( ...
    "Batch stride for estimating the whitening matrix: every nskip-th batch is used.", ...
    "The whitening covariance is averaged over that subset of batches.", ...
    "Smaller uses more batches: a steadier estimate, a slower start. Larger is faster but noisier.", ...
    "25 suits long recordings. For a short one (few batches) lower it so that several batches are used: 20 batches with nskip 25 use only one.", ...
    "25");
H.batch_size = entry( ...
    "Number of samples in each batch of data.", ...
    "The unit of processing: filtering, whitening, drift estimation (one estimate per batch) and template matching all go batch by batch.", ...
    "Larger batches mean fewer, longer drift time bins and more GPU memory. Smaller ones track drift more finely but have more edge effects and fewer spikes each.", ...
    "Keep about 2-4 s of data (the pipeline's 120000 is 4 s at 30 kHz). Lower it when the GPU runs out of memory.", ...
    "60000");
H.batch_downsampling = entry( ...
    "Number of batches skipped for each batch used: 10 uses every 10th batch.", ...
    "Thins the batches the whole sort uses.", ...
    "Above 1 throws data away: spikes in the skipped batches are not sorted.", ...
    "Keep 1. Raise it only for a quick test sort.", ...
    "1");
H.nt = entry( ...
    "Number of samples in each spike waveform (template width), also the padding for filtering. Must be odd.", ...
    "Sets the snippet length for the templates, the PC features and the template matching.", ...
    "Too short cuts off the waveform's tail; too long adds noise and compute.", ...
    "61 is about 2 ms at 30 kHz. At other sampling rates keep about 2 ms (an odd number). With templates_from_data off, nt must stay 61.", ...
    "61");
H.nt0min = entry( ...
    "Sample index, within the nt-sample waveform, at which spikes are aligned (their peak or trough). Blank = auto.", ...
    "Aligns snippets and templates; spike times are reported at this point of the waveform.", ...
    "Moves how much of the waveform comes before and after the peak.", ...
    "Leave blank: Kilosort4 uses int(20 * nt / 61), 20 for nt = 61. Change it only with an unusual nt.", ...
    "blank = int(20 * nt / 61)");
H.shift = entry( ...
    "Constant added to the data before every other step (data = data * scale + shift). Blank = none.", ...
    "Brings data of another scale (float32, for example) into the range Kilosort4 expects, about -100 to +100.", ...
    "Changes every raw amplitude, artifact_threshold included.", ...
    "Leave blank: the pipeline's .bin is int16 ADC counts, which Kilosort4 expects.", ...
    "blank (none)");
H.scale = entry( ...
    "Factor the data are multiplied by before every other step (data = data * scale + shift). Blank = none.", ...
    "Brings data of another scale (float32, for example) into the range Kilosort4 expects, about -100 to +100.", ...
    "Changes every raw amplitude, artifact_threshold included.", ...
    "Leave blank: the pipeline's .bin is int16 ADC counts, which Kilosort4 expects.", ...
    "blank (none)");

% --- Drift correction ---------------------------------------------------
H.nblocks = entry( ...
    "Number of non-overlapping blocks along the probe for drift correction (Kilosort4 adds nblocks - 1 blocks in the overlaps). 0 = no drift correction, 1 = rigid, more = non-rigid.", ...
    "Estimates how the probe moved over time by registering each batch's spike depth / amplitude histogram, then shifts the data back.", ...
    "Corrects slow probe movement that would split units over time. With few or widely spaced sites the estimate is unreliable and can add movement that was not there.", ...
    "0 for 64 sites or fewer, or rows 50 um or more apart; 1 for more closely spaced sites; 5 for a single shank of 2 mm or more (Neuropixels). Optimize for probe sets it from the layout.", ...
    "1");
H.binning_depth = entry( ...
    "Vertical bin size, in um, of the depth histogram used for drift estimation.", ...
    "Sets the depth resolution of the drift estimate.", ...
    "Smaller is finer but noisier; larger is steadier but coarser.", ...
    "Keep 5 for dense probes. Only used when nblocks > 0.", ...
    "5");
H.sig_interp = entry( ...
    "Spatial smoothness scale, in um, of the interpolation that shifts the data by the drift estimate.", ...
    "Width of the Gaussian kernel used to resample the channels at their drift-corrected positions.", ...
    "Larger blurs the signal over more sites; smaller can leave gaps on sparse probes.", ...
    "Keep it close to the site spacing (20 suits Neuropixels-like probes). Only used when nblocks > 0.", ...
    "20");
H.drift_smoothing = entry( ...
    "Three Gaussian smoothing widths for the drift estimate, one per axis of its correlation array: correlation, time and depth block (in Kilosort4's documented order).", ...
    "Smooths the batch-by-block drift estimate before it is applied.", ...
    "More smoothing gives a steadier drift trace but misses fast movement; less follows noise. The depth smoothing has no effect with nblocks = 1.", ...
    "Keep 0.5, 0.5, 0.5. Raise the time smoothing when the drift trace is jittery on noisy data. Kilosort4 advises against changing the correlation axis.", ...
    "0.5, 0.5, 0.5");
H.dmin = entry( ...
    "Vertical spacing, in um, of the template centers used for spike detection. Blank = auto (the median vertical spacing of the sites).", ...
    "Places the grid of universal templates that detection scans with; the same grid groups templates for clustering.", ...
    "Smaller makes a denser grid: more templates, slower. Larger can miss spikes centered between grid points.", ...
    "Blank or the probe's row pitch. Optimize for probe sets the row pitch.", ...
    "blank = auto");
H.dminx = entry( ...
    "Horizontal spacing, in um, of the template centers used for spike detection.", ...
    "Places the columns of the universal-template grid.", ...
    "Smaller makes a denser grid: more templates, slower. Larger can miss spikes between columns. No effect when every shank is a single column.", ...
    "32 suits Neuropixels 1 and 2. For other probes start from the median lateral distance between contacts; Optimize for probe sets it.", ...
    "32");

% --- Spike detection ----------------------------------------------------
H.Th_universal = entry( ...
    "Detection threshold for the universal (generic) templates, in units of the whitened data. Th(1) in earlier Kilosorts.", ...
    "The first detection pass: spikes matching the universal templates above it seed the clustering and feed the drift estimate.", ...
    "Lower finds smaller units and more noise clusters; higher finds fewer, cleaner units and misses small ones.", ...
    "Usually 6-10. Raise it when the sort has many noise clusters; lower it when known units are missed. The pipeline uses 7 (Kilosort4's 9) to keep small units on low-channel-count probes.", ...
    "9");
H.Th_learned = entry( ...
    "Detection threshold for the learned templates in the final template matching, in units of the whitened data. Th(2) in earlier Kilosorts.", ...
    "Matching pursuit keeps a spike for a learned template when the match exceeds it.", ...
    "Lower assigns more spikes, small and noisy ones included; higher gives cleaner units with fewer spikes.", ...
    "Usually 7-10. Lower it when a unit's amplitude histogram is cut off at the low end.", ...
    "8");
H.Th_single_ch = entry( ...
    "Single-channel threshold, in standard deviations of the whitened data, for the crossings used to learn the universal templates.", ...
    "Collects the single-channel snippets whose k-means shapes become the universal templates (with templates_from_data on).", ...
    "Lower lets noise shapes into the templates; higher learns from fewer, larger spikes.", ...
    "Rarely needs changing.", ...
    "6");
H.nearest_chans = entry( ...
    "Number of nearest channels considered for each template and spike.", ...
    "Finds local maxima during spike detection, and sets how many channels each spike's PC features cover.", ...
    "More widens the spatial footprint (more compute and memory); fewer loses spatial information that separates units.", ...
    "10 suits most probes. It cannot exceed the number of sites (Kilosort4 caps it); Optimize for probe does so.", ...
    "10");
H.nearest_templates = entry( ...
    "Number of nearest template locations considered when finding local maxima during spike detection.", ...
    "Decides whether a detection is the best match among its neighboring template locations.", ...
    "More compares against more neighbors (slower); fewer can keep duplicate detections of one spike.", ...
    "On probes of 64 sites or fewer keep it at most the number of sites, for numerical stability; Optimize for probe does so.", ...
    "100");
H.max_channel_distance = entry( ...
    "Distance, in um, beyond which a template is dropped when no channel is that close. Also limits the channels compared during clustering.", ...
    "Removes template centers that sit too far from any site.", ...
    "Too small drops templates between widely spaced sites, so spikes there are missed. Too large keeps templates off the probe.", ...
    "At least about half the largest gap between neighboring sites. Raise it on sparse probes.", ...
    "32");
H.max_peels = entry( ...
    "Maximum number of matching-pursuit iterations over each batch.", ...
    "Each iteration subtracts the matched spikes and searches the residual again.", ...
    "More resolves more overlapping spikes, at more run time.", ...
    "100 is almost always enough. Raise it only for very high firing rates or dense overlap.", ...
    "100");
H.templates_from_data = entry( ...
    "Whether the waveform shapes of the universal templates are learned from the data or taken from Kilosort4's built-in set.", ...
    "On: k-means of single-channel snippets (Th_single_ch, n_templates). Off: the predefined shapes.", ...
    "Learned shapes fit the recording's spikes better; the built-in set is steadier when there are few spikes.", ...
    "Keep on. Off requires nt = 61.", ...
    "true");
H.n_templates = entry( ...
    "Number of single-channel waveform shapes in the universal templates (with templates_from_data on).", ...
    "The number of k-means clusters fitted to the single-channel snippets.", ...
    "More covers more waveform variety, at more compute and more chance of fitting noise.", ...
    "Keep 6.", ...
    "6");
H.n_pcs = entry( ...
    "Number of single-channel principal components used for spike features (with templates_from_data on).", ...
    "Each spike is described by its projection on these PCs on its nearest channels; clustering works on those features.", ...
    "More keeps more waveform detail, at more memory; fewer can merge units with similar shapes.", ...
    "Keep 6.", ...
    "6");
H.template_sizes = entry( ...
    "Number of spatial sizes of the universal templates, as multiples of min_template_size.", ...
    "Each template location is scanned with Gaussian spatial envelopes of these widths.", ...
    "More sizes match a wider range of spike footprints, at more compute.", ...
    "Keep 5.", ...
    "5");
H.min_template_size = entry( ...
    "Standard deviation, in um, of the smallest Gaussian spatial envelope of the universal templates.", ...
    "The base width of the template footprints (template_sizes multiples of it).", ...
    "Too small fits spikes that span several sites poorly; too large blurs neighboring units together.", ...
    "About half the distance to the nearest contact, not below 10. Optimize for probe sets it; the pipeline uses 15.", ...
    "10");

% --- Clustering & postproc ---------------------------------------------
H.acg_threshold = entry( ...
    "Fraction of refractory-period violations, in a unit's autocorrelogram relative to its baseline, that a unit may have.", ...
    "Labels units good (else mua) in Kilosort4's KSLabel, and picks the units considered for merging.", ...
    "Lower is stricter: fewer units are labeled good.", ...
    "0.2 is the default; Kilosort4's code notes 0.1 for stricter criteria.", ...
    "0.2");
H.ccg_threshold = entry( ...
    "Fraction of refractory-period violations, in the cross-correlogram of two units relative to its baseline, below which they may merge.", ...
    "Two units whose CCG shows a refractory dip (they look like one neuron) are merged.", ...
    "Higher merges more pairs (risks merging different neurons); lower merges fewer (more oversplit units).", ...
    "Keep 0.25. Lower it when distinct units are merged; raise it when one neuron comes out split.", ...
    "0.25");
H.cluster_neighbors = entry( ...
    "Number of nearest neighbor spikes found for each spike when building the clustering graph.", ...
    "Sets the connectivity of the graph that clustering partitions.", ...
    "More gives a denser graph (smoother, larger clusters), at more memory and run time; fewer can fragment units.", ...
    "Keep 10. Changes alter resource use and sorting time.", ...
    "10");
H.cluster_downsampling = entry( ...
    "Inverse fraction of spikes used as landmarks in clustering: 20 uses every 20th spike.", ...
    "Neighbors are searched among the landmarks only (up to max_cluster_subset).", ...
    "Higher uses fewer landmarks: less memory, but small units can be lost. Lower uses more memory and time.", ...
    "Kilosort4 reports 5-20 working well. Lower it to keep small units when memory allows.", ...
    "20");
H.max_cluster_subset = entry( ...
    "Maximum number of spikes used per clustering center when searching for nearest neighbors.", ...
    "Caps the landmark subset so it does not grow without bound in long recordings (cluster_downsampling is raised on the fly to stay under it).", ...
    "Larger costs memory and time with little gain; smaller can lose small units.", ...
    "Keep 25000.", ...
    "25000");
H.x_centers = entry( ...
    "Number of horizontal positions of the centers that group templates for clustering. Blank in Kilosort4 = auto from peaks in channel density.", ...
    "Templates are clustered in groups around these centers (it does not place the detection templates).", ...
    "Too few makes very large groups (slow, more memory); too many can split a unit across groups.", ...
    "One per shank, or one per about 200 um of a wider shank. Optimize for probe sets it.", ...
    "blank = auto");
H.cluster_init_seed = entry( ...
    "Random seed of the kmeans++ initialization of the clustering.", ...
    "Fixes the starting point of the clustering so a sort is reproducible.", ...
    "Another seed gives slightly different clusters.", ...
    "Leave it. Change it only to check how stable a sort is.", ...
    "5");
H.duplicate_spike_ms = entry( ...
    "Window, in ms, within which a later spike of the same unit is taken as a duplicate and removed. 0 = off.", ...
    "Removes double detections of one spike after template matching.", ...
    "Too large removes real spikes in bursts.", ...
    "Keep 0.25 ms, well below the refractory period.", ...
    "0.25");
H.position_limit = entry( ...
    "Maximum distance, in um, between channels used to estimate spike positions after sorting.", ...
    "Channels farther away get no weight in the spike position estimate.", ...
    "Changes only the estimated positions (spike_positions), not the sort.", ...
    "Keep 100.", ...
    "100");
end


function e = entry(definition, func, impact, tuning, ks4default)
%entry  One parameter's help.
e = struct('definition', definition, 'function', func, 'impact', impact, ...
    'tuning', tuning, 'ks4default', ks4default);
end
